"""Archipelago support, first part: the multiworld's names and ids for every check and item of this randomizer, and the
apworld package (worlds/lost_woods) that lets Archipelago place items over several worlds with our logic.

    python -m rando.archipelago <romfs> <out.apworld>   (from the HookshotRando folder)

Not yet: the game-side receiving of items and the client (docs/ARCHIPELAGO.md has the plan). Ids are stable across versions:
a hash of the name, so a check keeps its id whatever is added around it (Archipelago needs ids fixed within a game)."""
import hashlib
import json
import os
import sys
import zipfile

GAME = "Ocarina of Time Remake (Lost Woods)"
ID_BASE = 0x4C57_0000_0000   # ("LW": ids of this game live in their own range)


def stable_id(kind, name):
    """an id from the name: fixed for ever, never colliding within a kind (checked by catalog())"""
    h = int.from_bytes(hashlib.sha256(("%s:%s" % (kind, name)).encode("utf-8")).digest()[:4], "big")
    return ID_BASE + (0 if kind == "location" else 1 << 32) + h


def item_name(actor):
    """the multiworld's name of a pool item (the remake actor's name made readable)"""
    from . import items as I
    special = {"TBox_Shield_Deku": "Deku Shield", "TBox_Shield_Hylian": "Hylian Shield", "Obj_Heart_Piece": "Piece of Heart",
               "Obj_Heart_Container": "Heart Container", "Obj_Armor_Zora": "Zora Tunic", "Item_GlassTruth": "Lens of Truth",
               "Item_HeavyBoot": "Iron Boots", "Item_HoverBoot": "Hover Boots", "Item_Hammer": "Megaton Hammer"}
    if actor in special:
        return special[actor]
    if actor.startswith("Item_Melody_"):
        return "Song: " + actor[len("Item_Melody_"):]
    for prefix in ("Item_", "TBox_", "Tbox_", "Obj_"):
        if actor.startswith(prefix):
            actor = actor[len(prefix):]
    return actor.replace("_", " ")


def catalog(setup):
    """{"locations": {name: {"id", "check"}}, "items": {name: {"id", "actor", "rg", "progression"}}} of a generate.Setup"""
    from . import items as I
    from .logic.search import item_info
    info = item_info()
    locations, items = {}, {}
    for l in setup.locs:
        name = l.name if l.name not in locations else "%s (%s)" % (l.name, l.id)
        locations[name] = {"id": stable_id("location", l.id), "check": l.id}
    pool = set(I.ITEMS) | {a for g in I.TIERS for a in g} | set(I.DUNGEON_ITEMS)
    for actor in sorted(pool):
        try:
            rg = I.soh_item(actor, "ForestTemple" if actor in I.DUNGEON_ITEMS else None)
        except (KeyError, ValueError):
            rg = "RG_NONE"
        items[item_name(actor)] = {"id": stable_id("item", actor), "actor": actor, "rg": rg,
                                   "progression": bool(info.get(rg, {}).get("progression"))}
    for kind, table in (("location", locations), ("item", items)):
        ids = [v["id"] for v in table.values()]
        if len(ids) != len(set(ids)):
            raise ValueError("two %ss with one id" % kind)
    return {"game": GAME, "locations": locations, "items": items}


WORLD_TEMPLATE = '''"""Archipelago world for the Ocarina of Time remake randomizer "Lost Woods" (generated by rando.archipelago; do not edit).

The logic is the randomizer's own (Ship of Harkinian's, adapted to the remake), shipped in this package (rando/, data/): a
location is reachable when the randomizer's search reaches its check with the items the player holds. One region; rules
cached per set of items. Items from other worlds are given in game by the client (not written yet: docs/ARCHIPELAGO.md)."""
import collections
import json
import pkgutil

from BaseClasses import Item, ItemClassification, Location, Region
from worlds.AutoWorld import World

CATALOG = json.loads(pkgutil.get_data(__name__, "catalog.json").decode("utf-8"))


class LostWoodsItem(Item):
    game = CATALOG["game"]


class LostWoodsLocation(Location):
    game = CATALOG["game"]


class LostWoodsWorld(World):
    """Ocarina of Time (Switch 2 remake) on Longshot, randomized with Ship of Harkinian's logic."""
    game = CATALOG["game"]
    item_name_to_id = {name: v["id"] for name, v in CATALOG["items"].items()}
    location_name_to_id = {name: v["id"] for name, v in CATALOG["locations"].items()}
    topology_present = False

    def create_item(self, name):
        v = CATALOG["items"][name]
        kind = ItemClassification.progression if v["progression"] else ItemClassification.filler
        return LostWoodsItem(name, kind, v["id"], self.player)

    def _reach(self, state):
        from .lw import reach
        have = collections.Counter()
        for name, n in state.prog_items[self.player].items():
            rg = CATALOG["items"].get(name, {}).get("rg")
            if rg and rg != "RG_NONE":
                have[rg] += n
        key = frozenset(have.items())
        cache = self.__dict__.setdefault("_reach_cache", {})
        if key not in cache:
            cache[key] = reach(have)
        return cache[key]

    def create_regions(self):
        menu = Region("Menu", self.player, self.multiworld)
        for name, v in CATALOG["locations"].items():
            loc = LostWoodsLocation(self.player, name, v["id"], menu)
            check = v["check"]
            loc.access_rule = lambda state, check=check: check in self._reach(state)
            menu.locations.append(loc)
        self.multiworld.regions.append(menu)

    def create_items(self):
        pool = CATALOG.get("pool", [])
        for name in pool[:len(CATALOG["locations"])]:
            self.multiworld.itempool.append(self.create_item(name))

    def fill_slot_data(self):
        return {"catalog_version": CATALOG.get("version", 1)}
'''


LW_HELPER = '''"""the randomizer's logic world, built once from the data shipped in the apworld"""
import json
import os
import pkgutil

_WORLD = []


def _json(name):
    return json.loads(pkgutil.get_data(__name__, "data/" + name).decode("utf-8"))


def world_for_ap():
    if not _WORLD:
        import sys
        import types
        try:
            import zstandard  # noqa: F401
        except ImportError:   # (only the romfs readers use it; Archipelago never calls them)
            sys.modules["zstandard"] = types.ModuleType("zstandard")
        from .rando import generate
        from .rando.logic.search import vanilla_items
        table, gifts = _json("locations.json"), _json("gifts.json")
        world = generate.make_world(table, gifts)
        # (what the game gives that is not shuffled: shops' purchases, the prizes left as they are: as generate.Setup)
        mapped = {e["rc"] for e in generate._entries(table, gifts) if e["rc"]}
        removed = set(table.get("removed", ()))
        fixed = {rc: rg for rc, rg in vanilla_items().items()
                 if rc not in mapped and rc not in removed and rc in world.location_ids}
        _WORLD.append((world, fixed))
    return _WORLD[0]


def reach(have):
    """the checks reachable with these items (a Counter of SoH items), the unshuffled prizes collected on the way"""
    import collections
    world, fixed = world_for_ap()
    final, _ = world.collect(collections.Counter(have), fixed)
    return world.reachable(final)
'''


def build_apworld(romfs, out_path):
    """the .apworld (a zip of worlds/lost_woods): the world, the catalog, the item pool and the randomizer's logic"""
    from . import generate, items as I
    from .formats import zs
    setup = generate.Setup(romfs, zs.Codec(romfs))
    cat = catalog(setup)
    cat["version"] = 1
    names = {v["actor"]: n for n, v in cat["items"].items()}
    cat["pool"] = [names[I.canonical(l.vanilla)] for l in setup.locs if I.canonical(l.vanilla) in names]
    here = os.path.dirname(os.path.abspath(__file__))
    with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("lost_woods/__init__.py", WORLD_TEMPLATE)
        z.writestr("lost_woods/catalog.json", json.dumps(cat, indent=1))
        z.writestr("lost_woods/lw.py", LW_HELPER)
        for d, dirs, files in os.walk(here):
            dirs[:] = [x for x in dirs if x != "__pycache__"]
            for f in files:
                if f.endswith(".py"):
                    rel = os.path.relpath(os.path.join(d, f), here)
                    z.write(os.path.join(d, f), "lost_woods/rando/" + rel.replace(os.sep, "/"))
        data = os.path.join(os.path.dirname(here), "data")
        for f in ("locations.json", "gifts.json"):
            z.write(os.path.join(data, f), "lost_woods/data/" + f)
    return cat


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    c = build_apworld(sys.argv[1], sys.argv[2])
    print("%s: %d locations, %d items" % (sys.argv[2], len(c["locations"]), len(c["items"])))
